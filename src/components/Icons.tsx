export const FileFormatIcon: FC<{ filename: string; className?: string }> = ({
  filename,
  className = "w-5 h-5",
}) => {
  const ext = filename.split(".").pop()?.toLowerCase();
  if (ext === "pdf") return <FileTextIcon className={`${className} text-rose-500`} />;
  if (ext === "pptx") return <PresentationIcon className={`${className} text-amber-500`} />;
  if (ext === "docx") return <FileTextIcon className={`${className} text-blue-500`} />;
  if (ext === "mp4") return <VideoIcon className={`${className} text-purple-500`} />;
  if (ext === "mp3") return <AudioIcon className={`${className} text-indigo-500`} />;
  return <FileTextIcon className={`${className} text-slate-500`} />;
};
